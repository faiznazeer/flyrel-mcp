// Regenerates public/globe-mask.js: one land/sea bit per point of a Fibonacci sphere.
// Land outlines are Natural Earth (public domain) via the world-atlas package:
//   npm i --no-save world-atlas topojson-client d3-geo && node scripts/generate-globe-mask.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const POINTS = 42000;
const GOLDEN_ANGLE = Math.PI * (3 - Math.sqrt(5));
const require = createRequire(import.meta.url);
const atlas = JSON.parse(readFileSync(require.resolve("world-atlas/land-50m.json")));
const land = feature(atlas, atlas.objects.land);

const bits = new Uint8Array(Math.ceil(POINTS / 8));
let count = 0;
for (let i = 0; i < POINTS; i += 1) {
  const y = 1 - (2 * i + 1) / POINTS;
  const angle = i * GOLDEN_ANGLE;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lon = (Math.atan2(Math.sin(angle), Math.cos(angle)) * 180) / Math.PI;
  if (geoContains(land, [lon, lat])) {
    bits[i >> 3] |= 1 << (i & 7);
    count += 1;
  }
}

const output = new URL("../public/globe-mask.js", import.meta.url);
writeFileSync(output, `// Generated by scripts/generate-globe-mask.mjs. Natural Earth land outlines (public domain).
export const POINTS = ${POINTS};
export const LAND_MASK = "${Buffer.from(bits).toString("base64")}";
`);
console.log(`${count} land points of ${POINTS}`);
